use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum Language {
    #[serde(rename = "en")]
    #[default]
    En,
    #[serde(rename = "it")]
    It,
    #[serde(rename = "es")]
    Es,
    #[serde(rename = "fr")]
    Fr,
    #[serde(rename = "de")]
    De,
    #[serde(rename = "zh")]
    Zh,
    #[serde(rename = "ja")]
    Ja,
}

impl Language {
    pub const ALL: [Language; 7] = [
        Language::En,
        Language::It,
        Language::Es,
        Language::Fr,
        Language::De,
        Language::Zh,
        Language::Ja,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            Language::En => "en",
            Language::It => "it",
            Language::Es => "es",
            Language::Fr => "fr",
            Language::De => "de",
            Language::Zh => "zh",
            Language::Ja => "ja",
        }
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Language::En => "English",
            Language::It => "Italiano",
            Language::Es => "Español",
            Language::Fr => "Français",
            Language::De => "Deutsch",
            Language::Zh => "中文",
            Language::Ja => "日本語",
        }
    }

    pub fn from_code(s: &str) -> Option<Language> {
        match s {
            "en" => Some(Language::En),
            "it" => Some(Language::It),
            "es" => Some(Language::Es),
            "fr" => Some(Language::Fr),
            "de" => Some(Language::De),
            "zh" => Some(Language::Zh),
            "ja" => Some(Language::Ja),
            _ => None,
        }
    }

    pub fn is_cjk(self) -> bool {
        matches!(self, Language::Zh | Language::Ja)
    }
}

pub fn tr(language: Language, english: &str) -> &str {
    match language {
        Language::En => english,
        Language::It => it(english),
        Language::Es => es(english),
        Language::Fr => fr(english),
        Language::De => de(english),
        Language::Zh => zh(english),
        Language::Ja => ja(english),
    }
}

